#include "title/clive_state.h"
#include "title/clive_hud.h"
#include <cassert>
#include <fstream>
#include <limits>
#include <iterator>

int main(int argc,char** argv) {
    using cafe::title::clive::Gauge;
    namespace clive=cafe::title::clive;
    Gauge captured;
    // This property has no opponent argument. Its complete path must depend
    // only on the captured variable and never invoke the native evaluator.
    clive::property(captured,clive::kContactGain,0x1000a,0);assert(captured.points==0);
    clive::property(captured,clive::kContactGain,0x1000a,1);assert(captured.points==10);
    clive::property(captured,clive::kContactGain,0x1000a,2);assert(captured.points==10);
    clive::property(captured,clive::kContactGain,0x20005,2);assert(captured.points==15);
    clive::property(captured,clive::kContactGain,0x300ff,3);assert(captured.points==15);
    clive::property(captured,clive::kGain,uint32_t(-200),0);assert(captured.points==0);
    assert(clive::grounded_victim(1) && clive::grounded_victim(2));
    assert(!clive::grounded_victim(0) && !clive::grounded_victim(0x400));
    Gauge p1,p2;
    assert(p1.level()==1 && !p1.at_least(50));
    // Whiffs do not call add; five source 1+4 hits unlock level 2.
    for(int n=0;n<4;++n)p1.add(10);
    assert(p1.level()==1);
    p1.add(10);assert(p1.at_least(50) && p1.level()==2);
    assert(p2.points==0); // mirrors/tag partners have independent state
    for(unsigned level=3;level<=5;++level) {
        for(int n=0;n<10;++n)p1.add(5); // blocked source 1+4
        assert(p1.level()==level && p1.at_least(50*(level-1)));
    }
    p1.add(std::numeric_limits<int32_t>::max());assert(p1.points==200);
    p1.add(-200);assert(p1.level()==1 && !p1.at_least(50));
    p1.add(std::numeric_limits<int32_t>::min());assert(p1.points==0);
    assert(!p1.at_least(201));
    p1.add(150);p1=Gauge{};assert(p1.points==0); // round/new-actor reset
    Gauge ultimate;ultimate.add(200);clive::property(ultimate,clive::kBegin,0,0);
    assert(clive::continuation(ultimate,200)); // resource predicate; native 2/46 validate the live contact
    assert(!clive::continuation(ultimate,201));
    Gauge charging;charging.add(40);clive::property(charging,clive::kBegin,0,0);charging.add(10);
    assert(!clive::continuation(charging,50)); // this hit earns the next level
    clive::property(charging,clive::kBegin,0,0);
    assert(clive::continuation(charging,50));
    namespace hud=clive::hud;
    hud::publish(0,50,true,true,1000);hud::publish(1,200,true,false,1000);
    assert(hud::snapshot(0,1100).visible && hud::snapshot(0,1100).points==50);
    assert(hud::snapshot(1,1100).points==200 && !hud::snapshot(1,1100).on_field);
    assert(!hud::snapshot(0,1750).visible && !hud::snapshot(4,1100).visible);
    hud::publish(0,0,false,false,1200);assert(!hud::snapshot(0,1201).visible);
    const auto image=hud::raster({true,true,50});
    assert(image.width==32 && image.height==38 && image.pixels.size()==32*38*4);
    const auto half=hud::raster({true,true,25}),full=hud::raster({true,true,200});
    auto at=[](const hud::Image& im,unsigned x,unsigned y,unsigned c) { return im.pixels[(y*im.width+x)*4+c]; };
    assert(at(half,4,34,0)==245 && at(half,15,34,0)==245);
    assert(at(half,16,34,0)==40 && at(half,27,34,0)==40);
    assert(at(full,4,34,0)==255 && at(full,27,34,0)==255);
    assert(at(image,3,34,3)==0 && at(image,28,34,3)==0 && at(image,4,33,3)==0);
    size_t drawn=0;
    for(size_t i=3;i<image.pixels.size();i+=4)if(image.pixels[i])++drawn;
    assert(drawn>0 && drawn<image.width*image.height); // transparent scene remains intact
    const auto bgra=hud::raster({true,true,200},1,true);
    assert(bgra.pixels[0]==140 && bgra.pixels[2]==255);
    const auto left=hud::position(0,1280,720,32),right=hud::position(1,1280,720,32);
    assert(left.x>1280/5 && right.x+32==1280-left.x && left.y==right.y);
    // Optional artifact for visual QA, generated by the production rasterizer.
    if(argc>=2) {
        if(argc>=3) {
            std::ifstream input(argv[2],std::ios::binary);
            std::vector<uint8_t> bytes{std::istreambuf_iterator<char>(input),{}};
            hud::digits.store(hud::read(bytes));
        }
        std::ofstream file(argv[1],std::ios::binary);
        file<<"P6\n320 76\n255\n";
        std::array<hud::Image,5> images;
        for(unsigned level=0;level<5;++level) {
            images[level]=hud::raster({true,true,level*50},2);
        }
        for(unsigned y=0;y<76;++y)for(unsigned level=0;level<5;++level)for(unsigned x=0;x<64;++x) {
            const uint8_t gray=(x/8+y/8)%2 ? 64 : 48;
            const auto* pixel=&images[level].pixels[(y*64+x)*4];
            uint8_t mixed[3];
            for(int c=0;c<3;++c)mixed[c]=uint8_t((pixel[c]*pixel[3]+gray*(255-pixel[3])+127)/255);
            file.write(reinterpret_cast<const char*>(mixed),3);
        }
    }
}
